// Delaney's hand-charted BORDER motifs. GENERATED FROM HER OWN CHARTED
// LIBRARY -- do not hand-edit and never re-chart these through an image or
// quantisation pipeline. Companion to hand-charted-fonts.ts; same encoding
// convention (one string per row, digits are colour roles, '0' = empty).
//
// Each border is charted ONCE as a bottom-left corner plus a partial run
// extending right (and, for "lShaped" borders, a second partial run
// extending up in the same left-hand columns) -- never a complete tile.
// hand-charted-border-tiling.ts turns this single corner+run chart into a
// full four-sided frame at any target size, by rotating the corner into all
// four physical corners and repeating the run to fill each edge.
//
// `tiling` selects which assembly method the corner+run needs:
//   "simple"            -- one motif repeats along a single horizontal run;
//                           rotate the whole corner+run strip 4 ways.
//   "spacerAlternating"  -- motifs are separated by a genuine blank spacer
//                           column, and colour ROLES swap on alternating
//                           motifs (Flowers: petal/centre invert each time).
//   "pieceList"          -- two DIFFERENT-width sub-motifs alternate (Poppy:
//                           a 5-wide and a 7-wide unit); the run must always
//                           stop on the narrower one so it never lands two
//                           wide motifs adjacent to a corner.
//   "lShaped"            -- the corner has its own real vertical-arm data,
//                           charted separately from the horizontal run (not
//                           a rotation of it) -- rotating a single 1D strip
//                           for this style produces a visibly wrong result.
//
// Every one of these was iterated against Delaney's own visual review and is
// LOCKED: Poppy, Flowers, Ladder, Interlock, Spades, Small Flowers,
// Scandi Double, Oak and Acorn. Do not adjust corner/runRepeat without her sign-off --
// several of these numbers look "close enough" but are wrong by exactly one
// column, which only shows up once a border is tiled to full size.

export type HandBorderTiling = "simple" | "spacerAlternating" | "pieceList" | "lShaped";

export type HandBorder = {
  id: string;
  label: string;
  tiling: HandBorderTiling;
  /** Native charted size (corner + partial run), not the finished frame size. */
  width: number;
  height: number;
  corner: { width: number; height: number };
  /** Repeat length along the run, in stitches. Unused ("simple" only) when the border has no clean repeat -- falls back to a 1-column repeat. */
  runRepeat?: number | null;
  /** "pieceList" only: widths of the alternating sub-motifs, e.g. [5, 7]. */
  pieceWidths?: number[];
  /** Rows of '0'/'1'/'2'/'3' -- colour role per stitch, '0' = empty. */
  rows: string[];
};

